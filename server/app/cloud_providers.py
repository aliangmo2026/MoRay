"""动态多厂商云端 Provider 注册表（UI 增删，统一经 8000 网关转发）。

为什么需要它：llm_proxy 原来只有一个 `cloud` 槽位（.env 的 MORAY_LLM_*），
换厂商要改环境变量并重启。这里把"用户自己加的服务商"存进 MoRay 自己的 SQLite，
网关按请求头/模型名动态取 base_url+key 转发——身份底座、记忆、Twin、预算闸门
仍然全部在 llm_chat 链路上，不绕过。

安全约束（与 BYOK 同一套）：
- base_url 只允许 http/https，且 host 解析出的每个 IP 都必须是公网地址
  （环回/私有/链路本地/保留/组播一律拒绝）→ 防 SSRF / 开放代理；
- api_key 只落本机 SQLite，接口只回 `…后4位`；
- 所有 SQL 走参数绑定，不拼接。

路由优先级（见 llm_proxy 的云端分支）：
    BYOK 透传(base_url+api_key) > X-Moray-Target-Provider > 模型名命中注册表 > .env 单槽位
"""

from __future__ import annotations

import io
import ipaddress
import os
import re
import socket
import sqlite3
import time
from pathlib import Path
from urllib.parse import urlsplit

from fastapi import APIRouter, Request
from fastapi.responses import JSONResponse

from . import db as _db

router = APIRouter(prefix="/api/cloud", tags=["cloud"])

_NAME_RE = re.compile(r"^[a-z0-9][a-z0-9_-]{0,31}$")
_MODEL_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._:/-]{0,79}$")

# dsh 用的是 pi-ai 的**静态**模型目录（不会去 /v1/models 发现），所以新增的模型必须
# 落进 profile 的 patch 文件，重启 Harness 后才会出现在模型选择器里。这里维护一段
# 带标记的托管块，写前备份、只替换标记区间。
_PROFILE_PATCH = Path(os.environ.get("MORAY_DSH_PROFILE_PATCH")
                      or r"D:\moray-home\profiles\web\cordis.patch.yml")
_MARK_BEGIN = "      # >>> moray-gateway-models (auto-generated by /api/cloud/providers; do not edit)"
_MARK_END = "      # <<< moray-gateway-models"
_ANCHOR = "      # ---- [2026-10-30] 原生 deepseek provider 已停用"


def _conn() -> sqlite3.Connection:
    conn = _db.connect()
    conn.execute(
        "CREATE TABLE IF NOT EXISTS cloud_providers ("
        " name TEXT PRIMARY KEY,"
        " display_name TEXT NOT NULL,"
        " base_url TEXT NOT NULL,"
        " api_key TEXT NOT NULL,"
        " models TEXT NOT NULL,"
        " created_at REAL NOT NULL,"
        " updated_at REAL NOT NULL)")
    return conn


def _norm_models(raw) -> list[str]:
    if isinstance(raw, str):
        parts = re.split(r"[,\n]", raw)
    elif isinstance(raw, (list, tuple)):
        parts = [str(x) for x in raw]
    else:
        parts = []
    out: list[str] = []
    for part in parts:
        model = part.strip()
        if model and model not in out:
            out.append(model)
    return out


def validate_base_url(raw: str) -> tuple[str | None, str | None]:
    """仅 http/https + 全部解析 IP 为公网。返回 (规范化 base, 错误)。"""
    value = str(raw or "").strip().rstrip("/")
    parts = urlsplit(value)
    if parts.scheme not in ("http", "https"):
        return None, "Base URL 仅支持 http/https"
    host = parts.hostname
    if not host:
        return None, "Base URL 缺少主机名（示例：https://api.moonshot.cn/v1）"
    try:
        infos = socket.getaddrinfo(host, None)
    except OSError:
        return None, "无法解析主机名：%s" % host
    for info in infos:
        try:
            ip = ipaddress.ip_address(info[4][0])
        except ValueError:
            return None, "主机名解析出非法地址：%s" % info[4][0]
        if not ip.is_global:
            return None, ("指向非公网地址（%s），已拒绝：本网关只转发公网服务商；"
                          "本地模型请用 ollama / custom_27b 槽位" % ip)
    return value, None


def _public_row(row: sqlite3.Row) -> dict:
    key = str(row["api_key"] or "")
    return {
        "name": row["name"],
        "display_name": row["display_name"],
        "base_url": row["base_url"],
        "models": _norm_models(row["models"]),
        "has_key": bool(key),
        "key_hint": ("…" + key[-4:]) if key else "",
        "updated_at": row["updated_at"],
    }


def list_providers() -> list[dict]:
    conn = _conn()
    try:
        rows = conn.execute(
            "SELECT name, display_name, base_url, api_key, models, updated_at "
            "FROM cloud_providers ORDER BY name").fetchall()
        return [_public_row(r) for r in rows]
    finally:
        conn.close()


def lookup_by_name(name: str) -> dict | None:
    slug = str(name or "").strip().lower()
    if not slug:
        return None
    conn = _conn()
    try:
        row = conn.execute(
            "SELECT name, display_name, base_url, api_key, models FROM cloud_providers "
            "WHERE name = ?", (slug,)).fetchone()
        if row is None:
            return None
        return {"name": row["name"], "display_name": row["display_name"],
                "base_url": row["base_url"], "api_key": row["api_key"],
                "models": _norm_models(row["models"])}
    finally:
        conn.close()


def lookup_by_model(model: str) -> dict | None:
    target = str(model or "").strip()
    if not target:
        return None
    conn = _conn()
    try:
        rows = conn.execute(
            "SELECT name, display_name, base_url, api_key, models FROM cloud_providers").fetchall()
        for row in rows:
            if target in _norm_models(row["models"]):
                return {"name": row["name"], "display_name": row["display_name"],
                        "base_url": row["base_url"], "api_key": row["api_key"],
                        "models": _norm_models(row["models"])}
        return None
    finally:
        conn.close()


def pick_target(request, model: str) -> dict | None:
    """按 头 > 模型名 选上游；都没有返回 None（回落 .env 单槽位）。"""
    header = str(getattr(request, "headers", {}).get("X-Moray-Target-Provider") or "").strip().lower()
    if header:
        hit = lookup_by_name(header)
        if hit:
            return hit
    return lookup_by_model(model)


def all_models() -> list[tuple[str, str, str]]:
    """[(模型名, 厂商标识, 厂商显示名)]，供 /v1/models 与托管块使用。"""
    out: list[tuple[str, str, str]] = []
    for provider in list_providers():
        for model in provider["models"]:
            out.append((model, provider["name"], provider["display_name"]))
    return out


def _render_block(entries: list[tuple[str, str, str]]) -> str:
    if not entries:
        return ""
    lines = [
        _MARK_BEGIN,
        "      moray-gateway:",
        "        apiKeyEnv: MORAY_LOCAL_KEY",
        "        displayName: MoRay 通用云端网关",
        "        api: openai-completions",
        "        baseURL: http://127.0.0.1:8000/v1",
        "        headers:",
        "          X-Moray-Provider: cloud",
        "        compat:",
        "          supportsDeveloperRole: false",
        "          maxTokensField: max_tokens",
        "          supportsUsageInStreaming: true",
        "        streamIdleTimeoutMs: 180000",
        "        models:",
    ]
    for model, owner, display in entries:
        lines.append("          - id: %s" % model)
        lines.append("            name: %s · %s" % (model, display or owner))
        lines.append("            contextWindow: 131072")
        lines.append("            maxTokens: 8192")
    lines.append(_MARK_END)
    return "\n".join(lines)


def sync_profile_models() -> tuple[bool, str]:
    """把注册表里的模型写进 profile patch 的托管块（写前 .bak）。"""
    entries = all_models()
    block = _render_block(entries)
    path = _PROFILE_PATCH
    if not path.is_file():
        return False, "profile 配置不存在：%s" % path
    text = io.open(path, "r", encoding="utf-8", newline="").read()

    begin = text.find(_MARK_BEGIN)
    end = text.find(_MARK_END)
    if begin >= 0 and end > begin:
        end += len(_MARK_END)
        if text[end:end + 1] == "\n":
            end += 1
        new_text = text[:begin] + (block + "\n" if block else "") + text[end:]
    else:
        anchor = text.find(_ANCHOR)
        if anchor < 0:
            return False, "找不到托管块锚点，请检查 profile 配置（未写入任何内容）"
        new_text = text[:anchor] + (block + "\n" if block else "") + text[anchor:]

    if new_text == text:
        return True, "profile 已是最新（%d 个模型）" % len(entries)

    backup = path.with_name(path.name + ".bak-%d" % int(time.time()))
    try:
        backup.write_bytes(path.read_bytes())
    except OSError:
        pass
    io.open(path, "w", encoding="utf-8", newline="").write(new_text)
    return True, "已同步 %d 个模型到 profile（重启 Harness 后出现在模型选择器）" % len(entries)


# ---------------- HTTP API ----------------

@router.get("/providers")
async def api_list_providers():
    try:
        return {"ok": True, "providers": list_providers()}
    except Exception as exc:  # noqa: BLE001
        return JSONResponse(status_code=500, content={"ok": False, "error": str(exc)})


@router.post("/providers")
async def api_upsert_provider(request: Request):
    try:
        body = await request.json()
    except Exception:  # noqa: BLE001
        return JSONResponse(status_code=400, content={"ok": False, "error": "请求体不是合法 JSON"})
    if not isinstance(body, dict):
        return JSONResponse(status_code=400, content={"ok": False, "error": "请求体必须是 JSON 对象"})

    name = str(body.get("name") or "").strip().lower()
    if not _NAME_RE.match(name):
        return JSONResponse(status_code=400, content={
            "ok": False, "error": "name 只能是小写字母/数字/下划线/短横线（1-32 位）"})

    display_name = str(body.get("display_name") or body.get("displayName") or name).strip()[:64]
    base_url, err = validate_base_url(body.get("base_url") or body.get("baseUrl") or "")
    if err:
        return JSONResponse(status_code=400, content={"ok": False, "error": err})

    api_key = str(body.get("api_key") or body.get("apiKey") or "").strip()
    models = _norm_models(body.get("models"))
    if not models:
        return JSONResponse(status_code=400, content={"ok": False, "error": "至少填一个模型名"})
    for model in models:
        if not _MODEL_RE.match(model):
            return JSONResponse(status_code=400, content={
                "ok": False, "error": "模型名不合法：%s" % model})

    conn = _conn()
    try:
        existing = conn.execute(
            "SELECT name, api_key FROM cloud_providers WHERE name = ?", (name,)).fetchone()
        if not api_key:
            if existing is None or not existing["api_key"]:
                return JSONResponse(status_code=400, content={"ok": False, "error": "API Key 不能为空"})
            api_key = existing["api_key"]

        # 模型名全局唯一，否则按名字路由会有歧义
        for other in conn.execute(
                "SELECT name, models FROM cloud_providers WHERE name <> ?", (name,)).fetchall():
            clash = set(models) & set(_norm_models(other["models"]))
            if clash:
                return JSONResponse(status_code=409, content={
                    "ok": False, "error": "模型名已被服务商 %s 占用：%s" % (other["name"], ", ".join(sorted(clash)))})

        now = time.time()
        if existing is None:
            conn.execute(
                "INSERT INTO cloud_providers (name, display_name, base_url, api_key, models, created_at, updated_at) "
                "VALUES (?, ?, ?, ?, ?, ?, ?)",
                (name, display_name, base_url, api_key, ",".join(models), now, now))
        else:
            conn.execute(
                "UPDATE cloud_providers SET display_name = ?, base_url = ?, api_key = ?, models = ?, updated_at = ? "
                "WHERE name = ?",
                (display_name, base_url, api_key, ",".join(models), now, name))
        conn.commit()
    finally:
        conn.close()

    synced, note = sync_profile_models()
    public = next((p for p in list_providers() if p["name"] == name), None)
    return {"ok": True, "provider": public, "profile_synced": synced, "note": note}


@router.delete("/providers/{name}")
async def api_delete_provider(name: str):
    slug = str(name or "").strip().lower()
    conn = _conn()
    try:
        cur = conn.execute("DELETE FROM cloud_providers WHERE name = ?", (slug,))
        conn.commit()
        removed = cur.rowcount
    finally:
        conn.close()
    if not removed:
        return JSONResponse(status_code=404, content={"ok": False, "error": "服务商不存在"})
    synced, note = sync_profile_models()
    return {"ok": True, "removed": slug, "profile_synced": synced, "note": note}
